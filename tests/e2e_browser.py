from pathlib import Path
from playwright.sync_api import sync_playwright
import json
from uuid import uuid4
title="Funnel review "+uuid4().hex[:6]
key=Path('/workspace/Evolvyn/.local/runtime.env').read_text().strip().split('=',1)[1]
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':1000})
 errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
 page.goto('http://127.0.0.1:5173/')
 print('Login',flush=True)
 page.get_by_text('Use private development token',exact=True).click()
 page.get_by_label('Workspace token').fill(key)
 page.get_by_role('button',name='Open workspace').click()
 print('Create business',flush=True)
 page.get_by_role('button',name='Add business').click()
 page.get_by_label('Business name').fill('Browser smoke SaaS')
 page.get_by_label('Product or service').fill('Demo task tracker')
 page.get_by_label('Business goal',exact=True).fill('Investigate lower paid conversion')
 page.get_by_role('button',name='Create business').click()
 page.get_by_role('dialog').wait_for(state='hidden')
 page.get_by_role('button',name='New project',exact=True).click()
 page.get_by_label('Project name',exact=True).fill('Activation improvement')
 page.get_by_label('Goal',exact=True).fill('Improve conversion using verified evidence')
 page.get_by_role('button',name='Create project',exact=True).click()
 page.get_by_text('Activation improvement',exact=True).last.wait_for()
 page.get_by_role('button',name='Close workspace panel').click()
 page.get_by_label('Project',exact=True).select_option(label='Activation improvement')
 page.get_by_label('Message Evolvyn').fill(title)
 page.locator('input[type=file]').set_input_files(['/workspace/Evolvyn/sample-data/funnel.csv','/workspace/Evolvyn/sample-data/customer-feedback.txt'])
 page.locator('.files').get_by_text('funnel.csv').wait_for()
 print('Run analysis',flush=True)
 page.get_by_label('Analysis mode').select_option('evidence')
 page.get_by_role('button',name='Run analysis').click()
 page.get_by_role('button',name='Approve & create brief').wait_for(timeout=160000)
 assert page.locator('table').inner_text().count('%')>=2
 assert page.locator('.recommendation').count()==3
 assert page.get_by_role('region',name='Business recommendations').is_visible()
 page.get_by_role('button',name='Review this action').nth(1).click()
 page.get_by_label('Action plan').fill('Interview customers; define a controlled onboarding experiment.')
 print('Approve',flush=True)
 page.get_by_role('button',name='Approve & create brief').click()
 page.get_by_role('button',name='Open saved experiment brief').click()
 page.get_by_role('heading',name='Approved experiment brief').wait_for()
 assert 'Interview customers' in page.get_by_role('dialog').inner_text()
 page.get_by_role('button',name='Close',exact=True).click()
 page.get_by_role('button',name='Tasks & action plans',exact=True).click()
 page.locator('.task-item').first.wait_for()
 page.locator('.task-item').first.get_by_label('Task status',exact=True).select_option('in_progress')
 page.locator('.task-item').first.get_by_label('Task work notes',exact=True).fill('Reviewing the cited source evidence.')
 page.locator('.task-item').first.get_by_role('button',name='Save task').click()
 page.get_by_role('button',name='Close workspace panel').click()
 print('Reload',flush=True)
 page.reload()
 page.get_by_role('button',name=title).click()
 page.get_by_role('button',name='Open saved experiment brief').wait_for()
 page.screenshot(path='/workspace/Evolvyn/.local/validation/workspace-desktop.png',full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 print('Reload',flush=True)
 page.reload()
 page.get_by_role('button',name='Open sidebar').click()
 page.get_by_role('button',name=title).click()
 page.get_by_label('Message Evolvyn').wait_for()
 page.screenshot(path='/workspace/Evolvyn/.local/validation/workspace-mobile.png',full_page=True)
 assert not errors,errors
 print(json.dumps({'browser':'Chromium','desktop':'PASS','mobile':'PASS','journey':['login','business creation','upload','background analysis','evidence','edit approval','artifact','refresh history'],'page_errors':errors}))
 demo=browser.new_page(viewport={'width':1280,'height':900})
 demo.goto('http://127.0.0.1:5173/')
 demo.get_by_role('button',name='Try a sample business').click()
 demo.get_by_role('button',name='Approve & create brief').wait_for(timeout=160000)
 assert demo.locator('.recommendation').count()>=1
 assert demo.locator('.markdown').last.inner_text().strip()
 demo.screenshot(path='/workspace/Evolvyn/.local/validation/sample-workspace.png',full_page=True)
 print('One-click isolated sample workspace: PASS')
 demo.close()
 browser.close()
