"""Live browser acceptance for persistent registries, graph execution and governance."""
from playwright.sync_api import sync_playwright, expect
from pathlib import Path
from uuid import uuid4
import os,re,json
base=os.getenv('EVOLVYN_TEST_URL','http://localhost:3000')
out=Path('/workspace/Evolvyn/.local/validation');out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1512,'height':1050},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base)
    page.get_by_role('button',name='Create account',exact=True).click()
    page.get_by_label('Workspace name',exact=True).fill('Northstar business workspace')
    page.get_by_label('Email',exact=True).fill('control-'+uuid4().hex[:8]+'@example.test')
    page.get_by_label('Password',exact=True).fill('acceptance-password-'+uuid4().hex)
    page.get_by_role('button',name='Create your workspace',exact=True).click()
    page.get_by_role('button',name='Add business',exact=True).click()
    page.get_by_label('Business name',exact=True).fill('Northstar Analytics')
    page.get_by_label('Business goal',exact=True).fill('Improve activation using measurable customer evidence')
    page.get_by_role('button',name='Create business',exact=True).click()
    page.get_by_role('dialog').wait_for(state='hidden')
    business=page.request.get(base+'/api/businesses').json()[0]
    project_response=page.request.post(base+'/api/projects',headers={'X-Requested-With':'Evolvyn'},data={'name':'Activation evidence review','business_id':business['id'],'goal':'Improve activation through a reviewed experiment','data_policy':'local_only'})
    assert project_response.ok,project_response.text()
    page.get_by_label('Message Evolvyn').fill('Analyze conversion evidence and recommend a measurable onboarding experiment')
    page.locator('input[type=file]').set_input_files('/workspace/Evolvyn/sample-data/funnel.csv')
    page.locator('.files').wait_for()
    page.get_by_label('Analysis mode').select_option('evidence')
    page.get_by_role('button',name='Run analysis').click()
    page.get_by_role('button',name='Approve & create brief').wait_for(timeout=30000)
    page.screenshot(path=str(out/'conversation-preview.png'),full_page=True)
    page.get_by_role('button',name=re.compile('^Agent control center')).click()
    page.get_by_role('heading',name='Connect your agent tools.').wait_for()
    for name,profile in [('Evidence utilities','evidence_utilities'),('Business strategy','business_strategy')]:
        page.get_by_label('Display name',exact=True).fill(name)
        page.get_by_label(re.compile('^Server profile')).select_option(profile)
        page.get_by_role('button',name='Register connection',exact=True).click()
        page.get_by_role('status').filter(has_text='Server registered').wait_for()
        card=page.locator('.server-card').filter(has_text=name)
        card.get_by_role('button',name='Check health',exact=True).click()
        expect(card.locator('.status-pill')).to_have_text('healthy',timeout=30000)
    page.screenshot(path=str(out/'mcp-registry-preview.png'))
    page.get_by_role('button',name=re.compile('^Tool registry')).click()
    page.get_by_label('Tool name',exact=True).fill('evidence.compare')
    page.get_by_label('Description',exact=True).fill('Compare observed conversion rates without claiming causality')
    server=next(s for s in page.request.get(base+'/api/mcp/servers').json() if s['profile']=='evidence_utilities')
    page.get_by_label(re.compile('^Healthy server')).select_option(server['id'])
    page.get_by_label(re.compile('^Discovered tool')).select_option('compare_rates')
    page.get_by_label('Capabilities',exact=True).fill('analytics.compare, business.metrics')
    page.get_by_label('Business entities',exact=True).fill('conversion, customer')
    page.get_by_role('button',name='Register tool',exact=True).click()
    page.get_by_role('status').filter(has_text='Persistent capability registered').wait_for()
    card=page.locator('article.control-card').filter(has=page.get_by_text('evidence.compare',exact=True))
    card.get_by_role('button',name='Invoke tool',exact=True).click()
    page.get_by_label('Tool arguments',exact=True).fill(json.dumps({'before':5,'after':6}))
    page.get_by_role('button',name='Run validated tool',exact=True).click()
    page.get_by_role('status').filter(has_text='Tool invocation completed').wait_for()
    expect(page.locator('.tool-result')).to_contain_text('change_percentage_points')
    page.get_by_role('button',name=re.compile('^Agent harness')).click()
    page.get_by_role('button',name='Generate execution plan',exact=True).click()
    page.get_by_role('status').filter(has_text='Goal decomposed').wait_for()
    page.get_by_role('button',name='Save graph',exact=True).click()
    page.get_by_role('status').filter(has_text='Graph validated and saved').wait_for()
    page.get_by_role('button',name='Run graph',exact=True).click()
    page.get_by_role('button',name='Approve & continue',exact=True).wait_for(timeout=30000)
    page.screenshot(path=str(out/'harness-approval-preview.png'))
    page.get_by_role('button',name='Approve & continue',exact=True).click()
    expect(page.locator('.control-card-heading .status-pill')).to_have_text('COMPLETED',timeout=30000)
    page.locator('.control-main').evaluate('(node) => { node.scrollTop=0; }')
    page.screenshot(path=str(out/'harness-preview.png'))
    page.get_by_role('button',name=re.compile('^Governance')).click()
    page.get_by_role('button',name='Save governance policy',exact=True).click()
    page.get_by_role('status').filter(has_text='Organization governance policy saved').wait_for()
    page.locator('select[name=access]').select_option('restricted')
    page.get_by_role('button',name='Save project access',exact=True).click()
    page.get_by_role('status').filter(has_text='Project resource access updated').wait_for()
    page.get_by_label('Denied tools',exact=True).fill('evidence.compare')
    page.get_by_role('button',name='Save governance policy',exact=True).click()
    page.get_by_role('status').filter(has_text='Organization governance policy saved').wait_for()
    denied=page.request.post(base+'/api/tool-registry/evidence.compare/invoke',headers={'X-Requested-With':'Evolvyn'},data={'arguments':{'before':5,'after':6}})
    assert denied.status==403
    page.get_by_label('Denied tools',exact=True).fill('')
    page.get_by_role('button',name='Save governance policy',exact=True).click()
    page.get_by_role('status').filter(has_text='Organization governance policy saved').wait_for()
    page.locator('.control-main').evaluate('(node) => { node.scrollTop=0; }')
    page.screenshot(path=str(out/'governance-preview.png'))
    page.reload()
    page.get_by_role('button',name=re.compile('^Agent control center')).click()
    expect(page.locator('.server-card')).to_have_count(2)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(out/'control-center-mobile.png'))
    assert not errors,errors
    print('PASS: account, upload, cited analysis, two real MCP servers, tool binding/invocation, graph planning/execution/approval, policy save, refresh persistence, desktop/mobile; no browser errors')
    browser.close()
