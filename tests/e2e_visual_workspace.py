"""Live UI regression: uploaded logos, contextual menus and existing agent actions."""
import os,re
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright,expect

root=Path(__file__).resolve().parents[1]
out=root/'.local/validation';out.mkdir(parents=True,exist_ok=True)
base=os.getenv('EVOLVYN_TEST_URL','http://localhost:3000')
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1536,'height':960});errors=[];missing=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('response',lambda r:missing.append(r.url) if '/assets/' in r.url and r.status>=400 else None)
    page.goto(base)
    page.get_by_role('button',name='Create account',exact=True).click()
    page.get_by_label('Workspace name',exact=True).fill('Visual workspace acceptance')
    page.get_by_label('Email',exact=True).fill('visual-'+uuid4().hex+'@example.test')
    page.get_by_label('Password',exact=True).fill('visual-password-'+uuid4().hex)
    page.get_by_role('button',name='Create your workspace',exact=True).click()
    page.get_by_role('heading',name=re.compile('Your next idea')).wait_for()
    expect(page.locator('.home-actions button')).to_have_count(3)
    page.screenshot(path=str(out/'workspace-refreshed-home.png'))
    menu=page.locator('.composer-add')
    menu.locator('summary').click()
    expect(menu.get_by_role('group',name='Files and workspace actions')).to_be_visible()
    page.screenshot(path=str(out/'workspace-add-menu.png'))
    page.keyboard.press('Escape')
    expect(menu.get_by_role('group')).to_be_hidden()
    menu.locator('summary').click()
    page.locator('main > header').click(position={'x':200,'y':20})
    expect(menu.get_by_role('group')).to_be_hidden()
    # Every menu action opens an existing working surface.
    menu.locator('summary').click()
    menu.get_by_role('button',name='Open Canvas',exact=False).click()
    studio=page.locator('.agent-workspace')
    studio.get_by_role('button',name='Automations',exact=True).click()
    expect(studio.get_by_role('heading',name='Conditional review',exact=True)).to_be_visible()
    studio.get_by_role('button',name='Close studio',exact=True).click()
    menu.locator('summary').click()
    menu.get_by_role('button',name='Connect an MCP server',exact=False).click()
    page.get_by_label('Search connector catalog').wait_for()
    cards=page.locator('.connector-market-card')
    expect(cards.locator('img.connector-logo')).to_have_count(5)
    assert cards.locator('img.connector-logo').evaluate_all('(xs)=>xs.every(x=>x.complete&&x.naturalWidth>0)')
    expect(cards.filter(has=page.get_by_role('heading',name='Shopify',exact=True))).to_contain_text('not connected')
    page.screenshot(path=str(out/'workspace-uploaded-connectors.png'))
    page.get_by_role('button',name='Close agent control center',exact=True).click()
    page.get_by_role('button',name='Key vault',exact=True).click()
    studio.get_by_label('Credential provider',exact=True).select_option('gemini')
    preview=studio.get_by_label('Selected credential provider',exact=True)
    expect(preview).to_contain_text('Gemini')
    assert preview.locator('img').evaluate('(x)=>x.complete&&x.naturalWidth===512')
    studio.get_by_label('Credential provider',exact=True).select_option('groq')
    expect(preview).to_contain_text('Groq')
    assert preview.locator('img').evaluate('(x)=>x.complete&&x.naturalWidth===554')
    page.screenshot(path=str(out/'workspace-model-logos.png'))
    studio.get_by_role('button',name='Close studio',exact=True).click()
    menu.locator('summary').click()
    with page.expect_file_chooser() as chooser:
        menu.get_by_role('button',name='Upload a local file',exact=False).click()
    chooser.value.set_files(str(root/'sample-data/ecommerce-sales.csv'))
    expect(page.locator('.files')).to_contain_text('Parsed sales data')
    page.get_by_label('Analysis mode').select_option('evidence')
    page.get_by_label('Message Evolvyn').fill('Calculate sales metrics and propose an evidence-based investigation.')
    page.get_by_role('button',name='Run analysis',exact=True).click()
    page.locator('.run-summary').get_by_role('button',name='Review action',exact=True).wait_for(timeout=45000)
    expect(page.get_by_label('Calculated e-commerce metrics').first).to_contain_text('45.10 USD')
    page.locator('.run-summary').get_by_role('button',name='Review action',exact=True).click()
    page.screenshot(path=str(out/'workspace-refreshed-results.png'))
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1')
    menu.locator('summary').click()
    box=menu.get_by_role('group').bounding_box()
    assert box['x']>=0 and box['x']+box['width']<=390,box
    page.screenshot(path=str(out/'workspace-refreshed-mobile.png'))
    assert not errors,errors
    assert not missing,missing
    browser.close()
print('VISUAL WORKSPACE PASS: local SVGs and seven supplied logos, menu keyboard/outside dismissal, Canvas and connector navigation, real CSV upload/metrics/approval, desktop/mobile, no asset failures or JS errors')
