"""Live browser integration: upload → growth review → design → real harness → source export."""
import os,re,json,zipfile
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright,expect

base=os.getenv('EVOLVYN_TEST_URL','http://localhost:3000')
root=Path(__file__).resolve().parents[1]
out=root/'.local/validation';out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1512,'height':1100});errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base)
    page.get_by_role('button',name='Create account',exact=True).click()
    page.get_by_label('Workspace name',exact=True).fill('Northstar evolution team')
    page.get_by_label('Email',exact=True).fill('evolution-'+uuid4().hex+'@example.test')
    page.get_by_label('Password',exact=True).fill('browser-evolution-password-'+uuid4().hex)
    page.get_by_role('button',name='Create your workspace',exact=True).click()
    page.get_by_role('heading',name=re.compile('Your next idea')).wait_for()
    # Create interview through the same public API, then exercise new integrations in the UI.
    headers={'X-Requested-With':'Evolvyn','Authorization':'Bearer cookie'}
    def api(path,data=None):
        response=page.request.post(base+'/api'+path,headers=headers,data=data) if data is not None else page.request.get(base+'/api'+path,headers=headers)
        assert response.ok,response.text()[:500]
        return response.json()
    product=api('/studio/products',{'name':'Northstar feedback','goal':'Understand customer needs and improve onboarding'})
    import ast
    QUESTIONS=next(ast.literal_eval(n.value) for n in ast.parse((root/"backend/product_studio.py").read_text()).body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=="QUESTIONS" for t in n.targets))
    for field,_,answer in QUESTIONS:product=api('/studio/products/'+product['id']+'/answers',{'field':field,'text':answer,'revision':product['revision']})
    page.locator('.home-actions').get_by_role('button',name=re.compile('^Build a product')).click()
    studio=page.locator('.agent-workspace')
    studio.get_by_role('button',name='Growth insights',exact=True).click()
    studio.get_by_role('button',name='Create evidence conversation',exact=True).click()
    expect(studio.get_by_label('Growth conversation')).not_to_have_value('')
    conversation=studio.get_by_label('Growth conversation').input_value()
    studio.get_by_label('Growth evidence file').set_input_files(str(root/'sample-data/customer-feedback.txt'))
    studio.get_by_role('status').filter(has_text='Evidence uploaded').wait_for()
    studio.get_by_label('Growth research query').fill('customer onboarding and pricing')
    studio.get_by_role('button',name='Analyze growth evidence',exact=True).click()
    studio.get_by_role('heading',name='Market discussion signal').wait_for()
    expect(studio).to_contain_text('No live market source requested')
    studio.locator('select[name=mode]').select_option('evidence')
    studio.get_by_role('button',name='Run specialist review',exact=True).click()
    studio.get_by_label('Growth decision').wait_for(timeout=30000)
    studio.get_by_label('Growth decision').fill('Test a shorter onboarding checklist. Measure activation from a customer baseline before expanding.')
    studio.get_by_role('button',name='Approve decision to memory',exact=True).click()
    studio.get_by_role('status').filter(has_text='Reviewed decision saved').wait_for()
    studio.locator('.studio-scroll').evaluate('el=>el.scrollTop=0')
    page.screenshot(path=str(out/'growth-insights.png'),full_page=True)
    studio.get_by_role('button',name='Canvas',exact=True).click()
    studio.get_by_label('Add page element').select_option('heading')
    studio.get_by_label('Block label').fill('Know your customers. Build what matters.')
    studio.get_by_label('Add page element').select_option('card')
    studio.get_by_label('Block label').fill('Customer signals and activation insights')
    block=studio.locator('.canvas-node').last.bounding_box()
    page.mouse.move(block['x']+30,block['y']+25);page.mouse.down();page.mouse.move(block['x']+100,block['y']+160,steps=8);page.mouse.up()
    studio.get_by_role('button',name='Freehand',exact=True).click()
    box=studio.get_by_label('Page design canvas').bounding_box()
    page.mouse.move(box['x']+100,box['y']+250);page.mouse.down();page.mouse.move(box['x']+220,box['y']+285,steps=8);page.mouse.up()
    studio.get_by_label('Canvas product').select_option(product['id'])
    studio.get_by_role('button',name='Save & apply design',exact=True).click()
    studio.get_by_role('status').filter(has_text='Applied design').wait_for()
    page.screenshot(path=str(out/'design-canvas.png'),full_page=True)
    canvas_id=studio.get_by_label('Saved canvas').input_value()
    assert canvas_id
    studio.get_by_role('button',name='Node workflow',exact=True).click()
    studio.get_by_label('Workflow conversation').select_option(conversation)
    expect(studio.get_by_label('Workflow conversation')).to_have_value(conversation)
    studio.get_by_label('Add workflow node').select_option('approval')
    approval=studio.get_by_label('Entry node').locator('option').last.get_attribute('value') or studio.get_by_label('Entry node').locator('option').last.inner_text()
    studio.locator('select[name=source]').select_option('review')
    studio.locator('select[name=target]').select_option(approval)
    studio.get_by_role('button',name='Add connection',exact=True).click()
    studio.get_by_label('Add workflow node').select_option('result')
    result=studio.get_by_label('Entry node').locator('option').last.inner_text()
    studio.locator('select[name=source]').select_option(approval)
    studio.locator('select[name=target]').select_option(result)
    studio.locator('select[name=when]').select_option('approved')
    studio.get_by_role('button',name='Add connection',exact=True).click()
    expect(studio.get_by_label('Workflow conversation')).to_have_value(conversation)
    studio.get_by_role('button',name='Save & run workflow',exact=True).click()
    studio.get_by_role('button',name='Approve exact pending action',exact=True).wait_for(timeout=30000)
    studio.get_by_role('button',name='Approve exact pending action',exact=True).click()
    studio.get_by_role('heading',name='Workflow execution · COMPLETED').wait_for(timeout=30000)
    page.screenshot(path=str(out/'executable-canvas.png'),full_page=True)
    studio.get_by_text('Advanced graph and loop budgets',exact=True).click()
    studio.get_by_label('Graph JSON').fill('null')
    studio.get_by_role('button',name='Apply graph JSON',exact=True).click()
    expect(studio.get_by_role('alert')).to_contain_text('Use a graph object')
    expect(studio.get_by_label('Executable workflow canvas')).to_be_visible()
    if not studio.get_by_role('button',name='Shared runtime',exact=True).is_visible():studio.locator('.studio-advanced-nav>summary').click()
    studio.get_by_role('button',name='Shared runtime',exact=True).click()
    studio.get_by_label('Ontology entity').select_option('product')
    expect(studio.locator('.capability-list')).to_contain_text('build_product')
    expect(studio.locator('.capability-list')).not_to_contain_text('analyze_business')
    page.screenshot(path=str(out/'shared-runtime.png'),full_page=True)
    studio.get_by_role('button',name='Build a product',exact=True).click()
    studio.get_by_role('button',name='Guided form · no model',exact=True).click()
    studio.get_by_label('Saved product',exact=True).select_option(product['id'])
    studio.get_by_role('button',name='Build product starter',exact=True).click()
    studio.get_by_role('button',name='Download source',exact=True).wait_for(timeout=30000)
    with page.expect_download() as download:studio.get_by_role('button',name='Download source',exact=True).click()
    target=out/'evolution-product.zip';download.value.save_as(target)
    with zipfile.ZipFile(target) as archive:
        assert 'evolvyn/backend/graph_harness.py' in archive.namelist()
        assert 'Know your customers.' in archive.read('frontend/src/spec.json').decode()
    studio.get_by_role('button',name='Canvas',exact=True).click()
    studio.get_by_label('Saved canvas').select_option(canvas_id)
    expect(studio.get_by_label('Page design canvas').locator('text').filter(has_text='HEADING')).to_be_visible()
    assert float(studio.locator('input').first.evaluate('e=>getComputedStyle(e).fontSize').replace('px',''))>=16
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(out/'canvas-mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),page.evaluate("Array.from(document.querySelectorAll('body *')).filter(e=>{const r=e.getBoundingClientRect();return r.right>innerWidth+2&&r.width>0}).slice(0,25).map(e=>({tag:e.tagName,cls:e.className,w:e.getBoundingClientRect().width,right:e.getBoundingClientRect().right}))")
    if not studio.get_by_role('button',name='Shared runtime',exact=True).is_visible():studio.locator('.studio-advanced-nav>summary').click()
    studio.get_by_role('button',name='Shared runtime',exact=True).click()
    expect(studio.get_by_role('heading',name='A connected runtime for every product.')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),page.evaluate("Array.from(document.querySelectorAll('body *')).filter(e=>{const r=e.getBoundingClientRect();return r.right>innerWidth+2&&r.width>0}).slice(0,25).map(e=>({tag:e.tagName,cls:e.className,w:e.getBoundingClientRect().width,right:e.getBoundingClientRect().right}))")
    assert not errors,errors
    print('EVOLUTION BROWSER PASS: upload → growth snapshot → specialist approval → page drawing → versioned design → executed graph → ontology filter → source export with runtime → persisted canvas → mobile and readable inputs')
    browser.close()
