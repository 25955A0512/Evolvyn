import { useEffect, useState } from "react";
import { MessageCircle, X, ArrowUp, Plus } from "lucide-react";
import ReactMarkdown from "react-markdown";
import type { client } from "../api";
import { ConnectorArt } from "./ConnectorGallery";
export function PlatformHelp({ api }: { api: ReturnType<typeof client> }) {
  const [open, setOpen] = useState(false),
    [thread, setThread] = useState<any>(null),
    [question, setQuestion] = useState(""),
    [status, setStatus] = useState<any>(null),
    [error, setError] = useState(""),
    [busy, setBusy] = useState(false);
  useEffect(() => {
    if (open)
      Promise.all([api.json("/help/status"), api.json("/help/threads")])
        .then(([a, b]) => {
          setStatus(a);
          if (!thread && b.length) setThread(b[0]);
        })
        .catch((e) => setError(e.message));
  }, [open]);
  return (
    <>
      <button
        className="help-launch"
        onClick={() => setOpen(!open)}
        aria-label="Ask platform help"
      >
        <MessageCircle size={19} />
        Help
      </button>
      {open && (
        <section
          className="help-panel"
          role="dialog"
          aria-label="Evolvyn platform help"
        >
          <header>
            <div>
              <strong>Ask Evolvyn</strong>
              <small>Platform guidance · separate service AI</small>
            </div>
            <button
              aria-label="New help conversation"
              onClick={() => {
                setThread(null);
                setError("");
              }}
            >
              <Plus size={17} />
            </button>
            <button
              aria-label="Close platform help"
              onClick={() => setOpen(false)}
            >
              <X size={19} />
            </button>
          </header>
          <div className="help-messages">
            {!thread?.messages.length && (
              <p>
                Ask how to use Evolvyn, connect tools or understand a workflow.
                Answers are generated by the configured support provider.
              </p>
            )}
            {status && !status.routes.some((r: any) => r.configured) && (
              <p role="status">
                Support AI is not configured. An administrator needs to add the
                private support keys and model IDs.
              </p>
            )}
            {thread?.messages.map((m: any, i: number) => (
              <article className={m.role} key={i}>
                <strong>{m.role === "user" ? "You" : "Evolvyn"}</strong>
                <ReactMarkdown>{m.text}</ReactMarkdown>
                {m.provider && (
                  <small>
                    <ConnectorArt name={m.provider} size={15} /> {m.provider} ·{" "}
                    {m.model}
                    {m.fallback ? " · fallback provider" : ""}
                  </small>
                )}
              </article>
            ))}
            {busy && <p role="status">Generating an answer…</p>}
            {error && (
              <p role="alert" className="error">
                {error}
              </p>
            )}
          </div>
          <form
            onSubmit={async (e) => {
              e.preventDefault();
              setBusy(true);
              setError("");
              try {
                const result = await api.json("/help/ask", {
                  method: "POST",
                  body: JSON.stringify({
                    question,
                    thread_id: thread?.id || null,
                  }),
                });
                setThread(result);
                setQuestion("");
              } catch (e: any) {
                setError(e.message);
                const history = await api.json("/help/threads").catch(() => []);
                if (history.length) setThread(history[0]);
              } finally {
                setBusy(false);
              }
            }}
          >
            <textarea
              aria-label="Ask about Evolvyn"
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              maxLength={3000}
              placeholder="How do I connect a tool?"
              required
            />
            <button
              className="primary"
              disabled={busy || !question.trim()}
              aria-label="Send help question"
            >
              <ArrowUp size={18} />
            </button>
          </form>
          <small>
            Uses Gemini → Groq support routing. Your workspace agents use their
            vault routes; this assistant cannot execute their tools.
          </small>
        </section>
      )}
    </>
  );
}
